import type { BrandTheme, Density as FoundationDensity, ThemeMode } from '@foundation/theme';
import { normalizeDesignConfig, type Accent, type DesignConfig, type Elevation, type FontFamily, type Radius, type Spacing, type TypeScale } from '../effects/config';

/**
 * Strict, data-only adapter to the PUBLIC Foundation ThemeProvider contract.
 * No CSS injection, arbitrary token keys, DOM mutation or global preference changes.
 * Only the existing BrandTheme / mode / density fields are exported to providers.
 */
export interface FoundationThemeProviderPreset {
  defaultMode: Exclude<ThemeMode, 'system'>;
  defaultDensity: FoundationDensity;
  brand: BrandTheme;
}

export interface FoundationThemeExport {
  format: 'foundation-pattern-atlas-theme';
  version: 1;
  providerProps: FoundationThemeProviderPreset;
  /** FoundationThemeProvider currently has no props for these two settings. */
  previewOnly: Pick<DesignConfig, 'motion' | 'speed'>;
}

const PRIMARY: Record<Accent, string> = {
  jade: '#11765c', blue: '#475bc5', coral: '#b34d42', amber: '#916113'
};
const RADIUS: Record<Radius, number> = { square: 4, soft: 16, round: 28 };
const FONT: Record<FontFamily, string> = {
  sans: 'Inter, "Noto Sans SC", system-ui, sans-serif',
  editorial: 'Georgia, "Noto Serif SC", serif',
  technical: 'ui-monospace, "SFMono-Regular", Consolas, monospace'
};
const FONT_SIZE: Record<TypeScale, number> = { small: 12, regular: 14, large: 16 };
const CONTENT_PADDING: Record<Spacing, number> = { tight: 12, balanced: 20, airy: 28 };
const SHADOW: Record<Elevation, string> = {
  flat: 'none',
  soft: '0 8px 26px rgba(18, 48, 39, 0.09)',
  strong: '0 18px 44px rgba(18, 48, 39, 0.20)'
};

/** Maps 8 of the 10 Atlas choices to real Foundation/AntD settings. */
export function toFoundationThemeExport(input: DesignConfig): FoundationThemeExport {
  const design = normalizeDesignConfig(input);
  const colorPrimary = PRIMARY[design.accent];
  const borderRadius = RADIUS[design.radius];
  const fontFamily = FONT[design.font];
  const boxShadow = SHADOW[design.elevation];
  return {
    format: 'foundation-pattern-atlas-theme',
    version: 1,
    providerProps: {
      defaultMode: design.surface,
      defaultDensity: design.density === 'compact' ? 'compact' : 'default',
      brand: {
        // Retain the documented legacy aliases, as well as public AntD tokens.
        primaryColor: colorPrimary,
        borderRadius,
        fontFamily,
        token: { colorPrimary, borderRadius, fontFamily, fontSize: FONT_SIZE[design.typeScale], boxShadow, boxShadowSecondary: boxShadow },
        layout: { contentPadding: CONTENT_PADDING[design.spacing] }
      }
    },
    previewOnly: { motion: design.motion, speed: design.speed }
  };
}

/**
 * Exportable usage example. The consumer should update its EXISTING root provider
 * (rather than create an extra global provider) if one is already present.
 */
export function foundationThemeUsageSource(input: DesignConfig): string {
  const { providerProps, previewOnly } = toFoundationThemeExport(input);
  return [
    '// Generated by Pattern Atlas. Review before integrating into your app.',
    "import { FoundationThemeProvider } from '@foundation/theme';",
    'import type { ReactNode } from \'react\';',
    '',
    `const themeProps = ${JSON.stringify(providerProps, null, 2)} as const;`,
    '',
    'export function ProjectTheme({ children }: { children: ReactNode }) {',
    '  return <FoundationThemeProvider {...themeProps}>{children}</FoundationThemeProvider>;',
    '}',
    '',
    '// If your app already has FoundationThemeProvider, update its brand/default props instead of nesting.',
    '// defaultMode/defaultDensity are FALLBACKS: saved user theme/density settings take precedence.',
    `// Not mapped to FoundationThemeProvider: motion=${previewOnly.motion}, speed=${previewOnly.speed}.`,
    '// Implement those two separately with CSS and prefers-reduced-motion; do not assume automatic support.'
  ].join('\n');
}
